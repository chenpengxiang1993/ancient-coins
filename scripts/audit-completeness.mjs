function normalize(name) {
  // 去除「-备注」后缀（如"乾亨通宝-南汉"→"乾亨通宝"），再去除常见通名后缀
  return name.split('-')[0];
}

function main() {
  console.log('=== 钱币种类完整性审计（只读）===\n');
  let totalMissing = 0;
  let totalExtra = 0;

  const files = fs
    .readdirSync(DYNASTIES_DIR)
    .filter((f) => /^\d+\.json$/.test(f))
    .sort((a, b) => parseInt(a) - parseInt(b));

  for (const f of files) {
    const idx = parseInt(f);
    const data = JSON.parse(fs.readFileSync(path.join(DYNASTIES_DIR, f), 'utf-8'));
    const names = data.coins.map((c) => normalize(c.name));
    const standard = (STANDARD[idx] || []).map(normalize);

    const missing = standard.filter((s) => !names.some((n) => n === s));
    const extra = names.filter((n) => !standard.some((s) => s === n));

    console.log(`【${data.dynasty}】${data.coins.length}枚`);
    if (missing.length) {
      console.log(`  ❌ 缺失 ${missing.length} 枚：${missing.join('、')}`);
      totalMissing += missing.length;
    } else {
      console.log(`  ✅ 完整性通过（${standard.length} 种标准内无缺失）`);
    }
    if (extra.length) {
      console.log(`  ⚠️  数据独有 ${extra.length} 枚（需人工复核）：${extra.join('、')}`);
      totalExtra += extra.length;
    }
    console.log('');
  }

  console.log('=== 汇总 ===');
  console.log(`缺失：${totalMissing}`);
  console.log(`数据独有（复核项）：${totalExtra}`);
}

main();
